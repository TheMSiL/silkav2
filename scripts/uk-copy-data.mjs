let missing = 0;
const vocabFiles = [
  ...readdirSync("src/data/uk").map((f) => `src/data/uk/${f}`),
  "src/lib/i18n/dictionaries/uk.ts",
];

for (const file of vocabFiles) {
  let source = readFileSync(file, "utf8");
  for (const [pattern, replacement] of VOCAB) source = source.replace(pattern, replacement);
  writeFileSync(file, source);
}

for (const [file, edits] of Object.entries(SENTENCES)) {
  let source = readFileSync(file, "utf8");
  for (const [from, to] of edits) {
    if (from === to || source.includes(to)) continue;
    if (!source.includes(from)) {
      console.error(`NOT FOUND in ${file}:\n  ${from}`);
      missing += 1;
      continue;
    }
    source = source.split(from).join(to);
  }
  writeFileSync(file, source);
}

if (missing > 0) {
  console.error(`\n${missing} replacement(s) did not match.`);
  process.exit(1);
}
